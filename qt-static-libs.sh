#!/bin/sh
# qt-static-libs.sh: helper for linking GRPN against a static Qt build.
#
# A static Qt has no pkg-config files and cannot load platform plugins
# at run time, so the plugins must be linked in and registered with
# Q_IMPORT_PLUGIN.  qmake's .prl files, installed next to each static
# library and plugin, list everything each one needs at link time.
#
#   qt-static-libs.sh libs PREFIX MAJOR PLUGIN...
#       print the linker arguments for Qt Widgets plus the plugins
#   qt-static-libs.sh imports PLUGIN...
#       print C++ source that registers the plugins
#
# PLUGIN is one of: xcb (X11), wayland, offscreen, minimal.

set -e

# the .prl files (relative to the Qt prefix) and class names for a plugin
plugin_prls() {
   case $1 in
      xcb)       echo plugins/platforms/libqxcb.prl ;;
      wayland)   echo plugins/platforms/libqwayland.prl plugins/wayland-shell-integration/libxdg-shell.prl ;;
      offscreen) echo plugins/platforms/libqoffscreen.prl ;;
      minimal)   echo plugins/platforms/libqminimal.prl ;;
      *) echo "qt-static-libs.sh: unknown platform plugin '$1'" >&2; exit 1 ;;
   esac
}
plugin_classes() {
   case $1 in
      xcb)       echo QXcbIntegrationPlugin ;;
      wayland)   echo QWaylandIntegrationPlugin QWaylandXdgShellIntegrationPlugin ;;
      offscreen) echo QOffscreenIntegrationPlugin ;;
      minimal)   echo QMinimalIntegrationPlugin ;;
      *) echo "qt-static-libs.sh: unknown platform plugin '$1'" >&2; exit 1 ;;
   esac
}

# the archive a .prl describes, then the libraries it needs
prl_libs() {
   prefix=$1 prl=$2
   dir=$(dirname "$prefix/$prl")
   sed -n 's/^QMAKE_PRL_TARGET *= *//p' "$prefix/$prl" | sed "s|^|$dir/|"
   sed -n 's/^QMAKE_PRL_LIBS *= *//p' "$prefix/$prl" | sed \
      -e "s|\\\$\\\$\\[QT_INSTALL_LIBS\\]|$prefix/lib|g" \
      -e "s|\\\$\\\$\\[QT_INSTALL_PLUGINS\\]|$prefix/plugins|g" \
      -e "s|\\\$\\\$\\[QT_INSTALL_PREFIX\\]|$prefix|g"
}

case $1 in
   libs)
      shift
      [ $# -ge 3 ] || { echo "usage: $0 libs PREFIX MAJOR PLUGIN..." >&2; exit 1; }
      prefix=$1 major=$2; shift 2
      # check everything first: errors inside the pipeline below
      # would not stop the build
      prls="lib/libQt${major}Widgets.prl"
      for plugin in "$@"; do prls="$prls $(plugin_prls "$plugin")" || exit 1; done
      for prl in $prls; do
         if [ ! -f "$prefix/$prl" ]; then
            echo "qt-static-libs.sh: $prefix/$prl not found; is this a static Qt $major with that plugin?" >&2
            exit 1
         fi
      done
      {
         for plugin in "$@"; do
            for prl in $(plugin_prls "$plugin"); do prl_libs "$prefix" "$prl"; done
         done
         prl_libs "$prefix" "lib/libQt${major}Widgets.prl"
      } | tr ' ' '\n' | grep -v '^$' |
      # Keep only the last copy of each argument: object files must
      # appear once, and an archive's last position is after everything
      # that uses it.
      awk '{ arg[NR]=$0; last[$0]=NR } END { for(i=1;i<=NR;i++) if(last[arg[i]]==i) print arg[i] }' |
      tr '\n' ' '
      echo
      ;;
   imports)
      shift
      echo "/* Generated by qt-static-libs.sh: the Qt plugins linked into this static build. */"
      echo "#include <QtPlugin>"
      for plugin in "$@"; do plugin_classes "$plugin" >/dev/null || exit 1; done
      for plugin in "$@"; do
         for class in $(plugin_classes "$plugin"); do echo "Q_IMPORT_PLUGIN($class)"; done
      done
      ;;
   *)
      echo "usage: $0 libs PREFIX MAJOR PLUGIN... | $0 imports PLUGIN..." >&2
      exit 1
      ;;
esac
